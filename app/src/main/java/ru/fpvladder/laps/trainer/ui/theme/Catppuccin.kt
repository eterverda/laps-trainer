/**
 * Maps a Catppuccin palette to a Material3 [ColorScheme].
 *
 * Background palette (<=3 colors):
 * - base      -> background / surface
 * - mantle    -> surfaceContainerHigh (app background)
 * - surface0  -> surfaceVariant / surfaceContainer
 *
 * Text palette (<=3 colors):
 * - text      -> onSurface / onBackground
 * - subtext0  -> onSurfaceVariant
 * - base      -> onPrimary / onSecondary / onTertiary / onError
 *
 * Accent / exception colors:
 * - blue      -> primary
 * - mauve     -> secondary
 * - pink      -> tertiary
 * - red       -> error
 * - overlay0  -> outline
 */
fun CatppuccinPalette.toColorScheme(): ColorScheme {
    return ColorScheme(
        primary = blue,
        onPrimary = base,
        primaryContainer = surface1,
        onPrimaryContainer = text,
        inversePrimary = lavender,

        secondary = mauve,
        onSecondary = base,
        secondaryContainer = surface1,
        onSecondaryContainer = text,

        tertiary = pink,
        onTertiary = base,
        tertiaryContainer = surface1,
        onTertiaryContainer = text,

        background = base,
        onBackground = text,
        onSurface = text,
        onSurfaceVariant = subtext0,

        surfaceTint = base,
        inverseSurface = text,
        inverseOnSurface = base,
        error = red,
        onError = base,
        errorContainer = surface1,
        onErrorContainer = red,
        outline = overlay0,
        outlineVariant = surface1,
        scrim = Color.Black.copy(alpha = 0.7f),

        surfaceBright = surface0,
        surface = base,
        surfaceVariant = mantle,
        surfaceDim = crust,

        surfaceContainerHighest = surface2,
        surfaceContainerHigh = surface1,
        surfaceContainer = surface0,
        surfaceContainerLow = base,
        surfaceContainerLowest = crust,
    )
}
